    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
    
    java.util.Date dFechaElaUtil = dtcFechaEla.getDate();
    java.util.Date dFechaVenUtil = dtcFechaVen.getDate();
    
    
    java.sql.Date dFechaEla = new java.sql.Date(dFechaElaUtil.getTime());
    java.sql.Date dFechaVen = new java.sql.Date(dFechaVenUtil.getTime());
    
    // Get other values
    String nombre = txtNombreProducto.getText().trim();
    int stock = Integer.parseInt(txtStockProducto.getText().trim()); 
    float precio = Float.parseFloat(txtPrecioProducto.getText().trim());
    String proveedor = (String) cmbProveedor.getSelectedItem();
    
    
    // Validate inputs
    if (!nombre.isEmpty() && stock > 0 && precio > 0
        && dFechaVen != null && dFechaEla != null ) {
        adm.ingresar(dFechaEla, dFechaVen, nombre, stock, precio, proveedor);
        txtContenido.append("Producto registrado correctamente.\n");
        JOptionPane.showMessageDialog(null, "Datos ingresados correctamente");
    } else {
        JOptionPane.showMessageDialog(null, "Existen campos vacíos o inválidos");
    }
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

